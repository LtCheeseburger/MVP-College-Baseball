"""Copy recompiled functions out of the generated code so a hook can change instructions inside them.

The recompiler writes each guest function as `X86_FUNC(__imp__sub_XXXXXXXX) { ... }` in
generated/game/x86_recomp.*.cpp, with a `// ADDR instruction` comment before the C of every instruction. A source
file that defines `X86_FUNC(sub_XXXXXXXX)` replaces that function (the generated one is only a weak alternate name),
so a copy of the body with an edited instruction changes the game without patching default.xbe (players' DLLs are
built from their own xbe). The recompiler sometimes emits the same instruction in several functions (shared tails),
so every function that contains an edited address is copied.

Each copy is named sub_XXXXXXXX_exp, and sub_XXXXXXXX itself becomes a switch: the copy while
expansion::Active() (an expanded database is installed, src/game/expansion.cpp), else the original __imp__ body, so
the stock database runs the stock code. CMakeLists.txt runs this after every recompile:

    python clone_func.py <generated dir> <spec.json> <out.cpp>

spec.json: {"includes": [...], "edits": [{"at": "990DF", "old": "0x12C000u", "new": "kDbBlock", "note": "..."},
            {"at": "93B0E", "all": true, "old": "0xCB2u", "new": "..."},                  (whole function)
            {"at": "500EF1", "after": "C statement(s)", "funcs": ["500E70"]}],   (inserted after the instruction,
            only in the listed functions)
            "wrapped": ["112BC0"]}   (the switch is named sub_XXXXXXXX_gen: a hand-written hook of that address
                                      calls it)
"""
import json
import re
import sys
from pathlib import Path

HEAD = re.compile(r"^X86_FUNC\(__imp__sub_([0-9A-F]{8})\) \{$", re.M)


def load_functions(gen: Path) -> dict[str, str]:
    funcs = {}
    for f in sorted(gen.glob("x86_recomp.*.cpp")):
        text = f.read_text()
        for m in HEAD.finditer(text):
            end = text.index("\n}\n", m.start())
            funcs[m.group(1)] = text[m.start():end + 3]
    return funcs


def instr_span(lines: list[str], at: str) -> tuple[int, int]:
    tag = f"// {at} "
    for i, line in enumerate(lines):
        if line.strip().startswith(tag):
            j = i + 1
            while j < len(lines) and not lines[j].strip().startswith("// ") and not re.match(r"loc_\w+:", lines[j]) \
                    and lines[j] != "}":
                j += 1
            return i + 1, j
    raise KeyError(at)


def apply(body: str, edit: dict) -> str:
    at = f"{int(edit['at'], 16):08X}"
    if edit.get("all"):
        if edit["old"] not in body:
            raise SystemExit(f"{at}: '{edit['old']}' not in function")
        return re.sub(re.escape(edit["old"]) + r"(?![0-9A-Za-z_])", edit["new"], body)
    lines = body.split("\n")
    a, b = instr_span(lines, at)
    if "after" in edit:
        lines[b:b] = ["\t" + edit["after"]]
        return "\n".join(lines)
    for k in range(a, b):
        if edit["old"] in lines[k]:
            lines[k] = lines[k].replace(edit["old"], edit["new"])
            return "\n".join(lines)
    raise SystemExit(f"{at}: '{edit['old']}' not in its code")


def main() -> None:
    gen, spec, out = Path(sys.argv[1]), json.loads(Path(sys.argv[2]).read_text()), Path(sys.argv[3])
    funcs = load_functions(gen)
    patched: dict[str, str] = {}
    notes: dict[str, list[str]] = {}
    for edit in spec["edits"]:
        at = f"{int(edit['at'], 16):08X}"
        owners = [name for name, body in funcs.items() if f"// {at} " in body]
        if "funcs" in edit:   # restrict to these functions (e.g. an edit that jumps to a label only one copy has)
            owners = [n for n in owners if n in {f"{int(x, 16):08X}" for x in edit["funcs"]}]
        if not owners:
            raise SystemExit(f"{at}: in no generated function")
        for name in owners:
            patched[name] = apply(patched.get(name, funcs[name]), edit)
            notes.setdefault(name, []).append(f"{at} {edit.get('note', '')}".strip())
    parts = ["// GENERATED by tools/expansion/clone_func.py from the recompiled default.xbe; do not edit, edit",
             "// tools/expansion/expansion_spec.json. Copies of game functions with single instructions changed (sub_X_exp)",
             "// and, for each, the function itself choosing the copy or the original by expansion::Active()."]
    # exported declarations first: the shared header declares every function without dllexport, and a function used
    # before its exported definition cannot gain the attribute
    wrapped = {f"{int(x, 16):08X}" for x in spec.get("wrapped", [])}
    switch = {n: f"sub_{n}_gen" if n in wrapped else f"sub_{n}" for n in patched}
    names = sorted(patched)
    parts += ['#include "cpu/x86_ops.h"', ""]
    parts += [f"X86_FUNC({switch[n]});" for n in names] + [f"X86_FUNC(sub_{n}_exp);" for n in names] + [""]
    parts += [f'#include "{i}"' for i in spec.get("includes", [])] + [""]
    parts += [f"X86_EXTERN_FUNC(__imp__sub_{n});" for n in names] + [""]
    for name in names:
        body = patched[name].replace(f"X86_FUNC(__imp__sub_{name})", f"X86_FUNC(sub_{name}_exp)", 1)
        parts += [f"// sub_{name}: " + "; ".join(sorted(set(notes[name]))), body, ""]
    for name in names:
        parts += [f"X86_FUNC({switch[name]}) {{",
                  f"    if (expansion::Active()) sub_{name}_exp(ctx, base);",
                  f"    else __imp__sub_{name}(ctx, base);",
                  "}", ""]
    out.write_text("\n".join(parts))
    print(f"{len(patched)} functions -> {out}")


if __name__ == "__main__":
    main()
